package adris.altoclef.anomaly;

/**
 * (2026-09-11 异常看门狗) 异常严重度。
 *
 * 分级只决定"要不要刷到游戏聊天", 不决定"要不要落盘" —— 所有等级的异常
 * 都会完整写进 anomaly.log。这样即使分级判断错了, 也不会丢掉现场证据。
 */
public enum AnomalySeverity {
    /** 值得留意, 未必是缺陷 (如远距离算路的短暂空窗)。只落盘, 不打扰人。 */
    NOTICE,
    /** 大概率有问题, 需要人看一眼。落盘 + 聊天短提示。 */
    WARN,
    /** 明确卡死或失效, 不处理会一直耗下去。落盘 + 聊天短提示。 */
    CRITICAL
}
